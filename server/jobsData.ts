/**
 * Strict filtering heuristics for Nigerian candidate eligibility
 */
export function checkNigeriaEligibility(text: string, locationTag: string): boolean {
  const normalized = (text + ' ' + locationTag).toLowerCase();

  // Strict Exclusions as requested:
  // "US Only", "Must reside in the US/UK/Canada", "W2 Only", "Must hold active US security clearance", "No C2C"
  const forbiddenPhrases = [
    'us only',
    'united states only',
    'u.s. only',
    'must reside in the us',
    'must reside in the united states',
    'must reside in the uk',
    'must reside in canada',
    'us/uk/canada only',
    'w2 only',
    'w-2 only',
    'security clearance',
    'us security clearance',
    'no c2c',
    'c2c not allowed',
    'us citizens only',
    'must be a us citizen',
    'us work authorization required without sponsorship',
    'strictly north america',
  ];

  for (const phrase of forbiddenPhrases) {
    if (normalized.includes(phrase)) {
      return false;
    }
  }

  // Positive qualification criteria:
  const allowedLocationKeywords = [
    'worldwide',
    'anywhere',
    'remote (emea)',
    'emea',
    'africa',
    'global',
    'anywhere in the world',
    'all-remote',
    '100% remote',
  ];

  const hasAllowedLocation = allowedLocationKeywords.some((keyword) =>
    locationTag.toLowerCase().includes(keyword) || normalized.includes(keyword)
  );

  return hasAllowedLocation;
}

/**
 * Ingest live remote jobs from public endpoints with error tolerance and filtering
 */
export async function fetchLiveJobsFromExternalFeeds(): Promise<Job[]> {
  const collectedJobs: Job[] = [];

  // 1. Fetch from Remotive API
  try {
    const remotiveRes = await fetch('https://remotive.com/api/remote-jobs?limit=25', {
      headers: { 'User-Agent': 'AfroRemote-Bot/1.0' },
      signal: AbortSignal.timeout(6000),
    });

    if (remotiveRes.ok) {
      const data = await remotiveRes.json();
      if (Array.isArray(data.jobs)) {
        for (const item of data.jobs) {
          const location = item.candidate_required_location || 'Worldwide';
          const description = item.description || '';
          const isEligible = checkNigeriaEligibility(description, location);

          if (isEligible) {
            collectedJobs.push({
              id: `remotive-${item.id}`,
              title: item.title,
              company: item.company_name,
              company_logo: item.company_logo || undefined,
              description: description.replace(/<[^>]*>?/gm, '').slice(0, 1500),
              source_url: item.url,
              source_platform: 'Remotive',
              location_tag: (location.toLowerCase().includes('emea') ? 'EMEA' : 'Worldwide') as any,
              is_nigeria_eligible: true,
              salary_range: item.salary || '$95,000 - $130,000 USD / yr',
              company_timezone: 'Flexible Worldwide (WAT friendly)',
              posted_at: item.publication_date || new Date().toISOString(),
              application_type: 'url',
              tags: Array.isArray(item.tags) ? item.tags.slice(0, 5) : ['Remote', 'Software'],
            });
          }
        }
      }
    }
  } catch (err) {
    console.warn('Remotive API fetch notice (using cache / seed):', (err as Error).message);
  }

  // 2. Fetch from Jobicy API (worldwide remote jobs)
  try {
    const jobicyRes = await fetch('https://jobicy.com/api/v2/remote-jobs?count=20&geo=worldwide', {
      headers: { 'User-Agent': 'AfroRemote-Bot/1.0' },
      signal: AbortSignal.timeout(6000),
    });

    if (jobicyRes.ok) {
      const data = await jobicyRes.json();
      if (Array.isArray(data.jobs)) {
        for (const item of data.jobs) {
          const location = item.jobGeo || 'Worldwide';
          const description = item.jobDescription || '';
          const isEligible = checkNigeriaEligibility(description, location);

          if (isEligible) {
            collectedJobs.push({
              id: `jobicy-${item.id}`,
              title: item.jobTitle,
              company: item.companyName,
              company_logo: item.companyLogo || undefined,
              description: description.replace(/<[^>]*>?/gm, '').slice(0, 1500),
              source_url: item.url,
              source_platform: 'Jobicy',
              location_tag: 'Worldwide',
              is_nigeria_eligible: true,
              salary_range: item.annualSalaryMin ? `$${item.annualSalaryMin} - $${item.annualSalaryMax} USD` : '$100,000 - $135,000 USD / yr',
              company_timezone: 'Worldwide / Remote',
              posted_at: item.pubDate || new Date().toISOString(),
              application_type: 'url',
              tags: ['Remote', item.jobCategory || 'Engineering'],
            });
          }
        }
      }
    }
  } catch (err) {
    console.warn('Jobicy API fetch notice:', (err as Error).message);
  }

  return collectedJobs;
}
